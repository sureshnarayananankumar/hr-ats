package com.businessgateways.hrats.security;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.security.crypto.argon2.Argon2PasswordEncoder;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The migration hinges on this: the Java backend must verify the
 * Argon2id hashes already written to hr_ats_db by the Node backend's
 * `argon2` library. If it cannot, all 249 existing users would have to
 * reset their password.
 *
 * Both sides emit the PHC string format
 * ($argon2id$v=19$m=...,t=...,p=...$salt$hash), which is self-describing:
 * the verifier reads the parameters out of the stored hash rather than
 * assuming its own. That is what makes cross-implementation verification
 * work at all.
 *
 * The fixture below was generated by the Node backend using the exact
 * settings in common/utils/crypto.util.ts. It is a throwaway vector for
 * a throwaway password, not a real credential.
 */
class Argon2CompatibilityTest {

    /**
     * Hash of "TestPassword123", produced by the Node argon2 library
     * with type=argon2id, memoryCost=19456, timeCost=2, parallelism=1.
     */
    private static final String NODE_HASH =
            "$argon2id$v=19$m=19456,t=2,p=1$n5Xheh5LruA1071/Pj+Huw"
                    + "$rmrVXdVijjUKrY4v2DY03OQtPyEHR/K0XMfj6G3XREY";

    private static final String PASSWORD = "TestPassword123";

    /**
     * Parameters match crypto.util.ts, so hashes WRITTEN by Java remain
     * verifiable by the Node backend while both run during the
     * migration.
     */
    private final Argon2PasswordEncoder encoder =
            new Argon2PasswordEncoder(16, 32, 1, 19456, 2);

    @Test
    @DisplayName("verifies an Argon2id hash generated by the Node backend")
    void verifiesNodeGeneratedHash() {
        assertTrue(
                encoder.matches(PASSWORD, NODE_HASH),
                "Spring Security must verify a hash produced by the Node argon2 library");
    }

    @Test
    @DisplayName("rejects the wrong password against a Node-generated hash")
    void rejectsWrongPassword() {
        assertFalse(encoder.matches("WrongPassword123", NODE_HASH));
    }

    @Test
    @DisplayName("emits the same PHC format the Node backend expects")
    void emitsCompatibleFormat() {
        String javaHash = encoder.encode(PASSWORD);

        assertTrue(
                javaHash.startsWith("$argon2id$v=19$m=19456,t=2,p=1$"),
                "Java-written hashes must carry the same parameters so the Node "
                        + "backend can still verify them: " + javaHash);
        assertTrue(encoder.matches(PASSWORD, javaHash));
    }

    @Test
    @DisplayName("salts every hash, so the same password hashes differently")
    void saltsEachHash() {
        assertFalse(encoder.encode(PASSWORD).equals(encoder.encode(PASSWORD)));
    }

    @Test
    @DisplayName("a malformed stored hash returns false rather than throwing")
    void malformedHashDoesNotThrow() {
        // A corrupt row must never become an authentication bypass, and
        // must not take the login endpoint down either.
        assertFalse(encoder.matches("anything", "not-a-real-hash"));
        assertFalse(encoder.matches("anything", ""));
    }
}
